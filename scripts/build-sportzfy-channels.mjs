#!/usr/bin/env node
// Rebuilds public/sportzfy-channels.m3u from a Sportzfy v32 runtime capture
// (the `sportzfy_tv_channels.json` file produced by the APK analysis that
// dumps decrypted channel data from the app).
//
// Selector — channels that play directly on the site and in the app with
// their captured metadata:
//   - HTTP 200 at capture time;
//   - plain HLS (`.m3u8`) with no request headers and no tokenApi, or
//   - DASH (`.mpd`) whose capture carries a ClearKey `api` pair (`KID:KEY`)
//     — written as an #EXTINF `clearkey` attribute; the site and app fetch
//     the same pair from the Worker's /api/drm/tv/:id route.
// Embed/tokenApi and header-gated servers are excluded until the player
// pipeline supports them.
//
// Usage:
//   node scripts/build-sportzfy-channels.mjs path/to/sportzfy_tv_channels.json

import { readFileSync, writeFileSync } from "node:fs";
import assert from "node:assert/strict";

const capturePath = process.argv[2];
assert.ok(capturePath, "usage: node scripts/build-sportzfy-channels.mjs <sportzfy_tv_channels.json>");
const capture = JSON.parse(readFileSync(capturePath, "utf8"));

const clean = (value) => String(value ?? "").replace(/[\r\n",]+/g, " ").replace(/\s+/g, " ").trim();
const clearKeyShape = /^[0-9a-f]{32}:[0-9a-f]{32}$/;

// Both capture shapes: sportzfy_tv_channels.json keeps `status`/`kind`
// directly on the server; the debug tv_channels.json keeps `check.status`
// and no `kind` (the URL extension decides).
const serverStatus = (server) => {
  const declared = Number(server.status ?? server.check?.status);
  return Number.isFinite(declared) ? declared : null;
};
const serverKind = (server) => {
  const declared = String(server.kind ?? "").trim().toLowerCase();
  if (declared) return declared;
  const url = String(server.stream ?? server.url ?? "");
  if (/\.mpd(\?|$)/i.test(url)) return "mpd";
  if (/\.m3u8(\?|$)/i.test(url)) return "m3u8";
  return "";
};

const picked = [];
for (const channel of capture) {
  let hisCount = 0;
  for (const server of channel.servers ?? []) {
    const url = String(server.stream ?? server.url ?? "").trim();
    const kind = serverKind(server);
    const key = clearKeyShape.test(String(server.api ?? "").trim().toLowerCase()) ? String(server.api).trim().toLowerCase() : "";
    const verified = serverStatus(server) === 200;
    if (!verified) continue;
    const isPlainHls = kind === "m3u8" && !Object.keys(server.headers ?? {}).length &&
      !String(server.tokenApi ?? "").trim();
    const isKeyedDash = kind === "mpd" && key;
    if (!isPlainHls && !isKeyedDash) continue;
    hisCount++;
    const suffix = hisCount > 1 ? " " + hisCount : "";
    picked.push({
      channelName: clean(channel.name) + suffix,
      logo: clean(channel.logo),
      url,
      clearkey: key
    });
  }
}

assert.ok(picked.length, "no verified plain-HLS or keyed-DASH channels found in the capture");

const header =
  "#EXTM3U\n" +
  "# Curated Sportzfy snapshot — generated by scripts/build-sportzfy-channels.mjs\n" +
  "# from a Sportzfy v32 runtime capture. Every URL was verified HTTP 200 with\n" +
  "# a valid manifest at capture time (" + new Date().toISOString().slice(0, 10) + ").\n" +
  "# clearkey holds the DASH channel's clearkey KID:KEY pair; the Worker merges\n" +
  "# it into the channel and serves it via /api/drm/tv/:id.\n" +
  "# Regenerate from a fresh capture when these hosts rotate their URLs.\n";

const lines = [header];
for (const entry of picked) {
  const attrs = [
    `tvg-name="${entry.channelName}"`,
    `tvg-logo="${entry.logo}"`,
    `group-title="Sportzfy"`
  ];
  if (entry.clearkey) attrs.push(`type="dash"`, `clearkey="${entry.clearkey}"`);
  lines.push(`#EXTINF:-1 ${attrs.join(" ")},${entry.channelName}`);
  lines.push(entry.url);
}
const text = lines.join("\n") + "\n";
writeFileSync(new URL("../public/sportzfy-channels.m3u", import.meta.url), text);
console.log("wrote public/sportzfy-channels.m3u: " + picked.length + " channels");
for (const entry of picked) console.log("  " + entry.channelName + (entry.clearkey ? " [clearkey]" : "") + " - " + entry.url.slice(0, 80));
