#!/usr/bin/env node
// Rebuilds public/sportzfy-channels.m3u from a Sportzfy v32 runtime capture
// (the `sportzfy_tv_channels.json` file produced by the APK analysis that
// dumps decrypted channel data from the app).
//
// Selector: only servers the capture marked HTTP 200 that are plain HLS
// (`.m3u8`) with no request headers and no tokenApi/ClearKey DRM — channels
// that play directly on the site and in the app without extra support.
// Encrypted-DASH (`.mpd`, needs ClearKey KID:KEY) and embed/tokenApi servers
// are excluded until the player pipeline carries DRM keys.
//
// Usage:
//   node scripts/build-sportzfy-channels.mjs path/to/sportzfy_tv_channels.json

import { readFileSync, writeFileSync } from "node:fs";
import assert from "node:assert/strict";

const capturePath = process.argv[2];
assert.ok(capturePath, "usage: node scripts/build-sportzfy-channels.mjs <sportzfy_tv_channels.json>");
const capture = JSON.parse(readFileSync(capturePath, "utf8"));

const clean = (value) => String(value ?? "").replace(/[\r\n",]+/g, " ").replace(/\s+/g, " ").trim();

const picked = [];
for (const channel of capture) {
  for (const server of channel.servers ?? []) {
    const url = String(server.url ?? "").trim();
    const kind = String(server.kind ?? "").trim().toLowerCase();
    if (server.status !== 200) continue;              // HTTP 200 at capture time
    if (kind !== "m3u8" || !/\.m3u8$/i.test(url)) continue;
    if (Object.keys(server.headers ?? {}).length) continue;
    if (String(server.tokenApi ?? "").trim()) continue;
    // One pick per channel: the first verified HLS server.
    if (picked.some(entry => entry.channelName === channel.name)) break;
    picked.push({ channelName: clean(channel.name), logo: clean(channel.logo), url });
    break;
  }
}

assert.ok(picked.length, "no verified plain-HLS channels found in the capture");

const header =
  "#EXTM3U\n" +
  "# Curated Sportzfy snapshot — generated by scripts/build-sportzfy-channels.mjs\n" +
  "# from a Sportzfy v32 runtime capture. Every URL was verified HTTP 200 with\n" +
  "# a valid HLS manifest at capture time (" + new Date().toISOString().slice(0, 10) + ").\n" +
  "# Regenerate from a fresh capture when these hosts rotate their URLs.\n";

const lines = [header];
for (const entry of picked) {
  lines.push(`#EXTINF:-1 tvg-name="${entry.channelName}" tvg-logo="${entry.logo}" group-title="Sportzfy",${entry.channelName}`);
  lines.push(entry.url);
}
const text = lines.join("\n") + "\n";
writeFileSync(new URL("../public/sportzfy-channels.m3u", import.meta.url), text);
console.log("wrote public/sportzfy-channels.m3u: " + picked.length + " channels");
for (const entry of picked) console.log("  " + entry.channelName + " - " + entry.url);
